# ==============================================================================
# File:      adjustSize.R
# Functions: adjustSize() [exported]
#
# Purpose:
#   Rescales the allocation (column SOLUZ) of the optimized strata so that the
#   total sample size equals a value given externally. Take-all strata
#   (CENS = 1) are kept as they are; in the other strata SOLUZ is multiplied
#   iteratively by a common factor until the target total is reached, without
#   exceeding the stratum population N and, when the size is reduced, without
#   going below minnumstr units.
# ==============================================================================

#' @title Adjustment of the sample size in case it is externally given
#'
#' @description
#' The optimisation step finds the best stratification that minimises the sample size under given precision constraints.
#' In some cases, the goal is not the minimisation of the sample size, as this value is given externally. Nonetheless, it is
#' still possible to perform the optimisation of the stratification, and then to proceed to an adjustment of the sample size
#' by increasing or decreasing it proportionally in each resulting stratum.
#'
#' @param size The value of the sample size given externally
#' @param strata The new (aggregated) strata generated by the function 'optimizeStrata'
#' @param cens Flag indicating the presence of a take-all stratum
#' @param minnumstr Indicates the minimum number of units that must be allocated in each stratum. Default is 2.
#'
#' @return
#' The strata generated by the function 'optimizeStrata', where the variable 'SOLUZ' has been adjusted by taking into account the total required sample size
#'
#' @author
#' Giulio Barcaroli
#'
#' @examples
#' \dontrun{
#' library(SamplingStrata)
#' data(swisserrors)
#' data(swissstrata)
#' solution <- optimizeStrata (
#'   errors = swisserrors,
#'   strata = swissstrata,
#' )
#' #
#' sum(solution$aggr_strata$SOLUZ)
#' # Adjustment of total sample size (decreasing)
#' adjustedStrata <- adjustSize(size=300,strata=solution$aggr_strata)
#' sum(adjustedStrata$SOLUZ)
#' # Adjustment of total sample size (increasing)
#' adjustedStrata <- adjustSize(size=500,strata=solution$aggr_strata)
#' sum(adjustedStrata$SOLUZ)
#' }
#'
#' @keywords survey
#' @export
adjustSize <- function (size, strata, cens=NULL, minnumstr = 2) 
{ 
  cens <- strata[strata$CENS == 1,]
  strata <- strata[strata$CENS == 0,]
  if (nrow(cens) > 0) size <- size - sum(cens$N)
  
  diff <- size - sum(strata$SOLUZ)
  diffrel <- diff / size
  
  round(sum(strata$SOLUZ) * 1/(1-diffrel)) + sum(cens$N)
  olddiff = 0
  diff <- round(size - sum(strata$SOLUZ))
  if (diff > 0) {
    while ( diff != olddiff) {
      olddiff = diff
      diffrel <- diff/size
      for (i in (1:nrow(strata))) {
        strata$SOLUZ[i] <- round(strata$SOLUZ[i] * 1/(1-diffrel),3)
        if (strata$SOLUZ[i] > strata$N[i]) strata$SOLUZ[i] <- strata$N[i]
      }
      diff <- round(size - sum(strata$SOLUZ))
      cat("\n",sum(strata$SOLUZ))
    }
  }
  
  if (diff < 0) {
    while ( diff != olddiff) {
      olddiff = diff
      diffrel <- diff/size
      for (i in (1:nrow(strata))) {
        strata$SOLUZ[i] <- round(strata$SOLUZ[i] * 1/(1-diffrel),3)
        if (strata$N[i] >= minnumstr & strata$SOLUZ[i] < minnumstr) strata$SOLUZ[i] <- minnumstr
        if (strata$N[i] == 1 & strata$SOLUZ[i] < 1) strata$SOLUZ[i] <- 1
      }
      diff <- round(size - sum(strata$SOLUZ))
      cat("\n",sum(strata$SOLUZ))
    }
  }
  if (nrow(cens) > 0) strata <- rbind(strata,cens)
  cat("\n Final adjusted size: ",sum(strata$SOLUZ))
  return(strata)
}